from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics.pairwise import cosine_similarity

# Vectorization des DCI pour permettre une recherche textuelle intelligente
vectorizer = TfidfVectorizer(analyzer='char_wb', ngram_range=(3, 5))
tfidf_matrix = vectorizer.fit_transform(df['DCI'].fillna(''))

def rechercher_equivalents(requete, top_n=10):
    requete_normalisee = normalize_text(requete)

    requete_vec = vectorizer.transform([requete_normalisee])
    similarites = cosine_similarity(requete_vec, tfidf_matrix).flatten()

    indices_pertinent = similarites.argsort()[::-1]

    resultats = []
    for idx in indices_pertinent:
        if similarites[idx] > 0.1:
            resultats.append({
                'Nom du Médicament': df.iloc[idx]['Nom du Médicament'],
                'DCI': df.iloc[idx]['DCI'],
                'Dosage': df.iloc[idx]['Dosage'],
                'Présentation': df.iloc[idx]['Présentation'],
                'Forme Galénique': df.iloc[idx]['Forme Galénique'],
                'Laboratoire': df.iloc[idx]['Laboratoire'],
                'Classe Thérapeutique': df.iloc[idx]['Classe Thérapeutique'],
                'Score de Similarité': round(similarites[idx], 4)
            })
        if len(resultats) >= top_n:
            break

    df_res = pd.DataFrame(resultats)
    return df_res

# Exemple de recherche d'équivalents pour le paracétamol
resultats_recherche = rechercher_equivalents("paracetamol", top_n=5)
